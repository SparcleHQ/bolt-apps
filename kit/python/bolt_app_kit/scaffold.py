"""The script-app scaffold: what every script app used to copy into its own file (argument words, JSON files, a guarded run,
the Back row and the generated app file's common head). Pure stdlib. An app keeps its own logic and calls these."""
import json
import os

from .rows import KitError, NOTE_VIEW, back_row, emit, error_row
from .text import clean_text


class Fail(Exception):
    """A read that failed in a way the app can show: `kind` is its own word (setup, auth, fail), `msg` is the plain sentence."""
    def __init__(self, kind, msg):
        Exception.__init__(self, msg)
        self.kind, self.msg = kind, msg


def s(v, n=120):
    """One clean line of a text value (anything else is blank)."""
    return clean_text(v, n) if isinstance(v, str) else ""


def json_loader(here, prefix):
    """load_json(name) for the app's own files: `json_loader(HERE, _PFX)("config.json")` reads <here>/<prefix>config.json."""
    def load_json(name):
        with open(os.path.join(here, prefix + name), "r", encoding="utf-8") as f:
            return json.load(f)
    return load_json


def split_args(argv, file_words, keep_dash=False):
    """The words the person typed. The last words are the helper files the command lists, not input: exactly that group is dropped.
    A lone `-` is the app file's placeholder for an empty word and is dropped unless keep_dash."""
    a = list(argv[1:])
    n = len(file_words)
    if len(a) >= n and [os.path.basename(x) for x in a[-n:]] == list(file_words):
        a = a[:-n]
    return a if keep_dash else [w for w in a if w != "-"]


def fixture_mode(default):
    """Sample mode: BOLT_APP_FIXTURE=1 or 0 decides, anything else leaves the config's default."""
    env = os.environ.get("BOLT_APP_FIXTURE")
    return (env == "1") if env in ("0", "1") else bool(default)


def back_to_overview(sub="Back to the overview"):
    return back_row(sub, view=NOTE_VIEW)


def run_guarded(main, argv):
    """Run main(argv). A row the contract refuses is the author's bug and is named; any other crash is one plain row, never a traceback
    (BOLT_APP_DEBUG, which `bolt-apps run` sets, sends the real error to the terminal)."""
    try:
        main(argv)
    except SystemExit:
        raise
    except KitError as e:
        emit([error_row("Row contract: %s" % clean_text(str(e), 200), title="This app could not run")])
    except Exception as e:
        if os.environ.get("BOLT_APP_DEBUG"):
            import traceback
            traceback.print_exc()
        emit([error_row("%s while building the rows. Run the script in a terminal to see why." % e.__class__.__name__)])


def indent(lines, n):
    return [" " * n + x for x in lines]


def tile_bind(ind):
    """The bind lines of a number tile that reads the row's kpi_* fields."""
    pad = " " * ind
    return [pad + 'title: "{{row.kpi_label}}"', pad + 'value: "{{row.kpi_value}}"', pad + 'unit: "{{row.kpi_unit}}"', pad + 'max: "{{row.kpi_max}}"', pad + 'subtitle: "{{row.kpi_note}}"',
            pad + 'badge: "{{row.kpi_badge}}"', pad + 'footer: "{{row.kpi_foot}}"']


def bridge_head(cfg, script, file_words, examples, nargs=3, systems=("macos", "linux", "windows")):
    """The first lines of a generated app file for a views app: identity, the typed words (view, arg, arg2, ...: `nargs` of them),
    one bridge command per system, and the list presentation up to `view_arg`. The app adds its widgets, views and actions."""
    app = cfg["app"]
    names = ["view"] + ["arg" if i == 1 else "arg%d" % i for i in range(1, nargs)]
    L = ["# Generated by: python3 scripts/" + script + " --emit-yaml (edit config.json, not this file)", "schema_version: 1", "runtime: bridge", "id: %s" % app["id"], "chip: %s" % app["chip"],
         "title: %s" % json.dumps(app["title"]), "icon: %s" % app["icon"], "description: %s" % json.dumps(app["description"]), "placeholder_examples: %s" % json.dumps(list(examples)),
         "emits: Generic", "args:"]
    L += ['  - { name: view, from: "query.word(0)", default: overview }'] + ['  - { name: %s, from: "query.word(%d)", default: "-" }' % (n, i) for i, n in enumerate(names) if i]
    L += ["bridge:", "  command:"]
    words = " ".join("{{scripts_dir}}/%s" % f for f in file_words)
    for osn in systems:
        L.append('    %s: "%s {{scripts_dir}}/%s %s %s"' % (osn, "python" if osn == "windows" else "python3", script, " ".join("{{%s}}" % n for n in names), words))
    L += ["  parse: json", "  timeout_seconds: %d" % app["timeout"], "presentation:", "  widget: list", "  title_field: title", "  subtitle_field: subtitle", "  view_arg: view"]
    return L


def bridge_yaml(head, widget, views, actions):
    """The whole app file text: the head, the app's default right pane (`widget`, lines), one right pane per view (`views`, name to lines) and the actions."""
    L = list(head) + ["  right_widget:"] + indent(widget, 4) + ["  views:"]
    for name, lines in views.items():
        L += ["    %s:" % name, "      right_widget:"] + indent(lines, 8)
    return "\n".join(L + ["actions:"] + list(actions)) + "\n"


