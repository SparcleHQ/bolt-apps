"""The script-app scaffold the kit now carries once (bolt_app_kit.scaffold): what every script app used to copy into its own file."""
import json, os, sys, tempfile, unittest
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import bolt_app_kit as k

WORDS = ("a__config.json", "a__fixtures.json", "a__bolt_app_kit.py")


class Helpers(unittest.TestCase):
    def test_fail_keeps_kind_and_message(self):
        e = k.Fail("auth", "key refused")
        self.assertEqual((e.kind, e.msg, str(e)), ("auth", "key refused", "key refused"))

    def test_split_args_drops_the_helper_file_group_and_dashes(self):
        argv = ["x.py", "services", "-", "bad"] + ["/s/" + w for w in WORDS]
        self.assertEqual(k.split_args(argv, WORDS), ["services", "bad"])
        self.assertEqual(k.split_args(["x.py", "-", "a"], WORDS), ["a"])
        self.assertEqual(k.split_args(["x.py", "-", "a"], WORDS, keep_dash=True), ["-", "a"])
        self.assertEqual(k.split_args(["x.py", "q"] + ["/s/" + w for w in WORDS[:2]], WORDS), ["q", "/s/" + WORDS[0], "/s/" + WORDS[1]])

    def test_json_loader_reads_the_prefixed_file(self):
        d = tempfile.mkdtemp()
        with open(os.path.join(d, "a__config.json"), "w", encoding="utf-8") as f:
            json.dump({"n": 1}, f)
        self.assertEqual(k.json_loader(d, "a__")("config.json"), {"n": 1})

    def test_s_cleans_strings_and_blanks_the_rest(self):
        self.assertEqual(k.s("a​b"), "ab")
        self.assertEqual(k.s(5), "")
        self.assertEqual(len(k.s("x" * 500, 20)), 20)

    def test_back_and_indent_and_tile_bind(self):
        self.assertEqual(k.back_to_overview()["title"], "Back")
        self.assertEqual(k.back_to_overview("Up")["subtitle"], "Up")
        self.assertEqual(k.indent(["a", "b"], 2), ["  a", "  b"])
        self.assertEqual(k.tile_bind(4)[0], '    title: "{{row.kpi_label}}"')
        self.assertEqual(len(k.tile_bind(0)), 7)

    def test_fixture_mode_env_wins_over_config(self):
        old = os.environ.get("BOLT_APP_FIXTURE")
        try:
            os.environ["BOLT_APP_FIXTURE"] = "1"
            self.assertTrue(k.fixture_mode(False))
            os.environ["BOLT_APP_FIXTURE"] = "0"
            self.assertFalse(k.fixture_mode(True))
            os.environ["BOLT_APP_FIXTURE"] = "maybe"
            self.assertTrue(k.fixture_mode(True))
            del os.environ["BOLT_APP_FIXTURE"]
            self.assertFalse(k.fixture_mode(False))
        finally:
            if old is None:
                os.environ.pop("BOLT_APP_FIXTURE", None)
            else:
                os.environ["BOLT_APP_FIXTURE"] = old


class Run(unittest.TestCase):
    def run_main(self, main):
        import importlib
        sc = importlib.import_module("bolt_app_kit.scaffold")
        got = []
        real = sc.emit
        sc.emit = lambda rows, **kw: got.append(rows)   # the real emit ends the process
        try:
            k.run_guarded(main, ["x.py"])
        finally:
            sc.emit = real
        return json.dumps(got)

    def test_a_crash_is_one_plain_row_never_a_traceback(self):
        def main(argv):
            raise ValueError("secret detail")
        out = self.run_main(main)
        self.assertIn("ValueError while building the rows", out)
        self.assertNotIn("secret detail", out)

    def test_a_contract_error_names_the_row_problem(self):
        def main(argv):
            raise k.KitError("bad row")
        self.assertIn("Row contract: bad row", self.run_main(main))

    def test_system_exit_passes_through(self):
        def main(argv):
            raise SystemExit(7)
        with self.assertRaises(SystemExit) as c:
            k.run_guarded(main, ["x.py"])
        self.assertEqual(c.exception.code, 7)


class Yaml(unittest.TestCase):
    CFG = {"app": {"id": "a", "chip": "a", "title": "T \"q\"", "icon": "Gauge", "description": "D", "timeout": 20}}

    def head(self, **kw):
        return k.bridge_head(self.CFG, "a__app.py", WORDS, ["Enter", "x y"], **kw)

    def test_head_matches_the_hand_written_block(self):
        h = self.head(nargs=3)
        self.assertEqual(h[0], "# Generated by: python3 scripts/a__app.py --emit-yaml (edit config.json, not this file)")
        self.assertIn('title: "T \\"q\\""', h)
        self.assertIn('placeholder_examples: ["Enter", "x y"]', h)
        self.assertIn('  - { name: arg2, from: "query.word(2)", default: "-" }', h)
        self.assertIn('    windows: "python {{scripts_dir}}/a__app.py {{view}} {{arg}} {{arg2}} {{scripts_dir}}/a__config.json {{scripts_dir}}/a__fixtures.json {{scripts_dir}}/a__bolt_app_kit.py"', h)
        self.assertEqual(h[-1], "  view_arg: view")
        self.assertIn("  timeout_seconds: 20", h)

    def test_two_args_and_two_systems(self):
        h = self.head(nargs=2, systems=("macos", "linux"))
        self.assertNotIn("arg2", " ".join(h))
        self.assertFalse(any(x.startswith("    windows:") for x in h))
        self.assertTrue(any(x.startswith("    linux: \"python3 ") and "{{view}} {{arg}} {{scripts_dir}}" in x for x in h))

    def test_assemble_adds_widget_views_and_actions(self):
        y = k.bridge_yaml(self.head(nargs=2), ["kind: card"], {"overview": ["kind: card"], "list": ["kind: table"]}, ["  - { id: copy }"])
        self.assertTrue(y.endswith("\n"))
        self.assertIn("  right_widget:\n    kind: card\n  views:\n    overview:\n      right_widget:\n        kind: card\n    list:\n      right_widget:\n        kind: table\nactions:\n  - { id: copy }\n", y)


if __name__ == "__main__":
    unittest.main()
