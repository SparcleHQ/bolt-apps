#!/usr/bin/env node
// build-ranking.mjs: add recognition counts to INDEX.json and write RANKING.md.
//
// Input: INDEX.json, written just before by the checker (`bolt-apps index apps --out INDEX.json`).
// For each app it counts thumbs-up reactions on:
//   - the merged pull requests that touched apps/<id>/, and
//   - the app's tracking issue, an issue titled exactly "app: <id>".
// It stores counts only: no usernames, no reaction lists, nothing about who voted.
// Gallery fetch counts ("added N times") come from the site when that counter exists; until
// then the field is null and RANKING.md says "not counted yet". Recognition only: nothing in
// this repository depends on these numbers.
//
// Env: GITHUB_TOKEN (read access), GITHUB_REPOSITORY (owner/name). Optional:
// GALLERY_COUNTS_URL, a JSON object {"<app id>": <count>} published by the site.
// Exit 1 on any API failure, so a stale ranking is never committed as if it were fresh.

import { readFileSync, writeFileSync } from "node:fs";

const repo = process.env.GITHUB_REPOSITORY;
const token = process.env.GITHUB_TOKEN;
if (!repo || !token) {
  console.error("build-ranking: GITHUB_REPOSITORY and GITHUB_TOKEN are required.");
  process.exit(1);
}

async function gh(path) {
  const res = await fetch(`https://api.github.com${path}`, {
    headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json" },
  });
  if (!res.ok) throw new Error(`GitHub API ${path}: ${res.status} ${await res.text()}`);
  return res.json();
}

async function all(path) {
  const out = [];
  for (let page = 1; ; page++) {
    const sep = path.includes("?") ? "&" : "?";
    const batch = await gh(`${path}${sep}per_page=100&page=${page}`);
    out.push(...batch);
    if (batch.length < 100) return out;
  }
}

const index = JSON.parse(readFileSync("INDEX.json", "utf8"));
const ids = index.apps.map((a) => a.listing.id);

// Merged PRs and the app folders each one touched.
const prs = (await all(`/repos/${repo}/pulls?state=closed`)).filter((p) => p.merged_at);
const votes = Object.fromEntries(ids.map((id) => [id, 0]));
for (const pr of prs) {
  const files = await all(`/repos/${repo}/pulls/${pr.number}/files`);
  const apps = [...new Set(files.filter((f) => f.filename.startsWith("apps/")).map((f) => f.filename.split("/")[1]))];
  if (!apps.length) continue;
  // The pulls list carries no reaction counts; the issue view of the same number does.
  const up = (await gh(`/repos/${repo}/issues/${pr.number}`)).reactions["+1"];
  for (const id of apps) if (id in votes) votes[id] += up;
}

// Tracking issues: "app: <id>".
const issues = (await all(`/repos/${repo}/issues?state=all`)).filter((i) => !i.pull_request);
for (const issue of issues) {
  const m = /^app: ([a-z0-9][a-z0-9-]{0,63})$/.exec(issue.title.trim());
  if (m && m[1] in votes) votes[m[1]] += issue.reactions["+1"];
}

let added = null;
if (process.env.GALLERY_COUNTS_URL) {
  const res = await fetch(process.env.GALLERY_COUNTS_URL);
  if (!res.ok) throw new Error(`gallery counts: ${res.status}`);
  added = await res.json();
}

for (const app of index.apps) {
  const id = app.listing.id;
  app.recognition = { votes: votes[id], added: added ? added[id] ?? 0 : null };
}
index.recognition_note = "Counts only, recognition only. No personal data. Nothing depends on them.";
writeFileSync("INDEX.json", JSON.stringify(index, null, 2) + "\n");

const rows = [...index.apps].sort(
  (a, b) => b.recognition.votes - a.recognition.votes || a.listing.id.localeCompare(b.listing.id),
);
const lines = [
  "# Bolt Apps ranking",
  "",
  "Generated by `.github/workflows/index.yml`. Do not edit by hand.",
  "",
  "Thumbs-up reactions on each app's pull requests and its tracking issue (`app: <id>`), and how",
  "many times it was added from the gallery. Counts only, no personal data. Recognition only:",
  "nothing depends on these numbers.",
  "",
  "| App | Tier | Votes | Added |",
  "|---|---|---|---|",
  ...rows.map(
    (a) =>
      `| [${a.listing.title}](apps/${a.listing.id}/) | ${a.listing.tier} | ${a.recognition.votes} | ${
        a.recognition.added ?? "not counted yet"
      } |`,
  ),
  "",
];
writeFileSync("RANKING.md", lines.join("\n"));
console.log(`build-ranking: ${rows.length} apps`);
