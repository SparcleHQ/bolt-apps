// Shared by the engine tests: builds an app that carries its own full copy of the engine (the form every example had before the engine was kept once).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnPython } from '../lib/python.mjs';
import { knownOldEngine } from '../lib/engine.mjs';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const CLI = path.join(REPO, 'toolkit/bin/bolt-apps.mjs');
export const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'bolt-engine-test-'));

/** A copy of an example app under a fresh folder, with scripts/<id>__engine.py made the old full copy and its app file generated by it. Returns the app folder. */
export function fullCopyApp(template = 'acme-dash', parent = tmp()) {
	const dir = path.join(parent, template);
	fs.cpSync(path.join(REPO, 'kit/examples', template), dir, { recursive: true });
	const sd = path.join(dir, 'scripts'), eng = path.join(sd, `${template}__engine.py`);
	fs.writeFileSync(eng, knownOldEngine());
	const r = spawnPython([eng, '--emit-yaml'], { cwd: sd, encoding: 'utf8', env: { ...process.env } });
	if (r.status !== 0) throw new Error(r.stderr);
	fs.writeFileSync(path.join(dir, 'utilities', `${template}.yaml`), r.stdout);
	return dir;
}

/** { relative path: file bytes as hex digest } for every file under dir. */
export function snapshot(dir) {
	const out = {};
	const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else out[path.relative(dir, p)] = fs.readFileSync(p).toString('hex'); } };
	walk(dir);
	return out;
}
